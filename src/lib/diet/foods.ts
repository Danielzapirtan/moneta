import type { Allergen, Food, Kind, Slot } from "@/lib/diet/types";

type Draft = {
  id: string;
  name: string;
  detail: string;
  slots: Slot[];
  role: "main" | "side";
  protein: number;
  carbs: number;
  fat: number;
  serving: string;
  kind: Kind;
  allergens?: Allergen[];
  med?: boolean;
  lowCarb?: boolean;
};

function dish(input: Draft): Food {
  const kcal = Math.round(input.protein * 4 + input.carbs * 4 + input.fat * 9);
  return {
    id: input.id,
    name: input.name,
    detail: input.detail,
    slots: input.slots,
    role: input.role,
    protein: input.protein,
    carbs: input.carbs,
    fat: input.fat,
    serving: input.serving,
    kind: input.kind,
    allergens: input.allergens ?? [],
    med: input.med ?? false,
    lowCarb: input.lowCarb ?? false,
    kcal,
  };
}

